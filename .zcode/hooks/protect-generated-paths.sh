#!/usr/bin/env bash
# Generated-path protection for Printorian (ZCode PreToolUse hook).
#
# Protocol: read the tool payload JSON from stdin, extract
# tool_input.file_path, and decide. Exit 0 = allow. Exit 2 = block; stderr is
# shown to the calling agent. Any parse failure exits 0 — a broken guard must
# not become a broken editor.
#
# Protected paths and how to regenerate each:
#   frontend/packages/api-client/src/generated/   the generated TypeScript API
#                                                 client (ADR-0005) — regen:
#                                                 backend: python tools/export_openapi.py --out openapi.json
#                                                 frontend: npm run generate:api
#   backend/openapi.json                          exported OpenAPI artifact of
#                                                 tools/export_openapi.py
#   docs/assets/banner.svg, banner-light.svg      generated by
#                                                 docs/assets/banner.sh so the
#                                                 VOID and PAPER variants cannot
#                                                 drift apart
#   backend/printers.local.toml                   printer LAN credentials
#                                                 (ADR-0014) — git-ignored, and
#                                                 an agent never writes
#                                                 credentials; a person does
#
# Regeneration happens through Bash, which this hook deliberately does not
# match. It only stops hand edits of the artifacts.

set -u

payload="$(cat)"

path="$(printf '%s' "$payload" | python3 -c '
import json, sys
try:
    data = json.load(sys.stdin)
except Exception:
    print("")
    sys.exit(0)
value = data.get("tool_input", {}).get("file_path", "") or ""
print(value.replace("\\", "/"))
' 2>/dev/null || true)"

if [ -z "$path" ]; then
  exit 0
fi

case "$path" in
  */frontend/packages/api-client/src/generated/*|frontend/packages/api-client/src/generated/*)
    echo "Blocked: '$path' is the generated API client (ADR-0005) — never hand-edit it. Regenerate instead:" >&2
    echo "  cd backend && python tools/export_openapi.py --out openapi.json" >&2
    echo "  cd frontend && npm run generate:api" >&2
    exit 2
    ;;
  */backend/openapi.json|backend/openapi.json)
    echo "Blocked: '$path' is an artifact of tools/export_openapi.py — regenerate it, do not edit it." >&2
    exit 2
    ;;
  */docs/assets/banner.svg|*/docs/assets/banner-light.svg)
    echo "Blocked: '$path' is generated by docs/assets/banner.sh so the VOID and PAPER banners cannot drift — regenerate, do not edit." >&2
    exit 2
    ;;
  */backend/printers.local.toml|backend/printers.local.toml)
    echo "Blocked: '$path' holds printer LAN credentials (ADR-0014) — agents never write credentials. A person maintains this file." >&2
    exit 2
    ;;
esac

exit 0
