async def main() -> None:
    settings = Settings()
    engine = create_async_engine(settings.database_url)
    factory = async_sessionmaker(engine, expire_on_commit=False)
    store = FilesystemObjectStore(settings.storage_root)
    clock = SystemClock()

    async with factory() as db:
        library = ModelLibrary(db, store, clock)
        for seed in SEEDS:
            if await db.scalar(select(CatalogModel).where(CatalogModel.slug == seed.slug)):
                print(f"  = {seed.slug} (already present)")
                continue

            # Through the real ingest path, so the geometry on the card is
            # measured by `analyse_stl` rather than asserted here.
            geometry = binary_stl(seed.triangles, f"printorian {seed.code}")
            asset = await library.ingest(geometry, filename=f"{seed.code.lower()}.stl")
            # The card's line drawing, projected from the same bytes — so the
            # grid shows the actual part rather than a placeholder cube.
            drawing = outline(geometry)

            difficulty, strength, accuracy, speed, supports, postprocessing = seed.bars
            model = CatalogModel(
                id=new_id(),
                slug=seed.slug,
                code=seed.code,
                title=seed.title,
                summary=seed.summary,
                category=seed.category,
                size_class=size_class_of(asset.width_mm, asset.depth_mm, asset.height_mm),
                difficulty=difficulty,
                strength=strength,
                accuracy=accuracy,
                speed=speed,
                supports=supports,
                postprocessing=postprocessing,
                author=seed.author,
                multicolor=seed.multicolor,
                tags=[],
                model_asset_id=asset.id,
                license="CC BY-NC",
                version="1.0",
                rating_sum=seed.rating[0],
                rating_count=seed.rating[1],
                print_count=seed.print_count,
                is_published=True,
                published_at=datetime(2026, 7, 12, tzinfo=UTC),
                preview=drawing,
                # Measured facts only for the ones marked printed. The others stay
                # null, which is what makes the storefront say so.
                last_printed_at=datetime(2026, 8, 9, tzinfo=UTC) if seed.printed else None,
                last_print_minutes=Decimal(141) if seed.printed else None,
                last_print_grams=(
                    (asset.volume_cm3 * Decimal("1.24")).quantize(Decimal("0.01"))
                    if seed.printed
                    else None
                ),
                last_price=Decimal(601) if seed.printed else None,
                last_printer_name="P-01" if seed.printed else "",
            )
            db.add(model)
            await db.flush()
            for code, suitability, note, recommended in seed.materials:
                db.add(
                    CatalogModelMaterial(
                        model_id=model.id,
                        material_code=code,
                        suitability=Suitability(suitability),
                        note=note,
                        is_recommended=recommended,
                    )
                )

            # ASCII only: this runs on a Windows console whose default code
            # page is cp1251, which cannot encode "×" — and a seed script that
            # crashes on its own progress line is worse than a plain one.
            print(
                f"  + {seed.slug}: {asset.triangle_count} triangles, "
                f"{asset.width_mm} x {asset.depth_mm} x {asset.height_mm} mm, "
                f"{asset.volume_cm3} cm3, "
                f"{'watertight' if asset.is_watertight else 'NOT WATERTIGHT'}"
            )
        await db.commit()

    await engine.dispose()
    print("done")


if __name__ == "__main__":
    asyncio.run(main())
