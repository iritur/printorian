# --------------------------------------------------------------- geometry


def _l_profile(length: float, height: float, thickness: float) -> list[Point]:
    """An L, as a closed polygon. The bracket's cross-section."""
    return [
        (0.0, 0.0),
        (length, 0.0),
        (length, thickness),
        (thickness, thickness),
        (thickness, height),
        (0.0, height),
    ]


def _u_profile(width: float, height: float, thickness: float) -> list[Point]:
    """A U — a tray seen end-on: floor with a wall at each side."""
    return [
        (0.0, 0.0),
        (width, 0.0),
        (width, height),
        (width - thickness, height),
        (width - thickness, thickness),
        (thickness, thickness),
        (thickness, height),
        (0.0, height),
    ]


def _stepped_profile(width: float, height: float, step: float) -> list[Point]:
    """A two-step outline, for the enclosure."""
    return [
        (0.0, 0.0),
        (width, 0.0),
        (width, height - step),
        (width - step, height - step),
        (width - step, height),
        (0.0, height),
    ]


def _bracket() -> list[Tri]:
    """The kit's `BRACKET_V4`: an L-section, 64 mm deep.

    A real part rather than a cube — the 3D view exists to show the viewer works
    on geometry somebody would actually print.
    """
    return extrude(_l_profile(length=128.0, height=44.0, thickness=6.0), 64.0)


def _stepped_case() -> list[Tri]:
    """A stepped enclosure, standing in for a Raspberry Pi case."""
    return extrude(_stepped_profile(width=96.0, height=30.0, step=8.0), 62.0)


def _tray() -> list[Tri]:
    """A U-section tray."""
    return extrude(_u_profile(width=220.0, height=45.0, thickness=6.0), 140.0)


def _clip() -> list[Tri]:
    """A small cable clip: the same L, much smaller."""
    return extrude(_l_profile(length=24.0, height=8.0, thickness=3.0), 12.0)


def binary_stl(triangles: list[Tri], header: str) -> bytes:
    """Write triangles as a binary STL.

    Normals are written as zero, which the format permits and every reader
    tolerates: the winding above is the authority on facing, and a stored normal
    that disagreed with it would be a second source of truth for the same fact.
    """
    out = bytearray(header.encode("ascii", "replace")[:80].ljust(80, b"\0"))
    out += struct.pack("<I", len(triangles))
    for tri in triangles:
        out += struct.pack("<3f", 0.0, 0.0, 0.0)
        for vertex in tri:
            out += struct.pack("<3f", *vertex)
        out += struct.pack("<H", 0)
    return bytes(out)


