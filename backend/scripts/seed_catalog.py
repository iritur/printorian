    code: str
    title: str
    summary: str
    category: ModelCategory
    triangles: list[Tri]
    #: (code, suitability, note, recommended) — the kit's «Подходящие материалы»
    #: columns that are editorial. Δ price and stock are read from inventory.
    materials: tuple[tuple[str, str, str, bool], ...]
    #: difficulty, strength, accuracy, speed, supports, postprocessing — 0–10
