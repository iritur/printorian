"""Seed the model library with real geometry.

Companion to `seed_materials.py`. Every model here is a **genuine binary STL**,
generated by this script and pushed through `ModelLibrary.ingest` — the same path
a customer upload takes — so the triangle count, bounding box, volume and
watertightness on each card are measured by `analyse_stl` rather than typed in.

That matters more than it sounds. The catalogue's whole claim is that its numbers
are facts; seeding it with invented dimensions would make the first thing anyone
sees a demonstration of the opposite.

    cd backend && .venv/Scripts/python scripts/seed_catalog.py

Idempotent: content-addressed storage means re-running costs one hash per model
and writes nothing new.
"""

